import { build } from "esbuild";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const banner = "/* Generated by frontend/build.mjs from frontend/src. Do not edit directly. Third-party licenses: THIRD_PARTY_LICENSES.txt */";
const common = {
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2022", "safari17", "chrome120", "firefox121"],
  jsx: "automatic",
  legalComments: "eof",
  charset: "utf8",
  define: { "process.env.NODE_ENV": "\"production\"" },
  banner: { js: banner },
  metafile: true,
  logLevel: "info",
};

const results = [
  await build({ ...common, entryPoints: ["src/navigation.jsx"], outfile: "../static/navigation.js" }),
  await build({ ...common, entryPoints: ["src/visuals.js"], outfile: "../static/visuals.js" }),
];

// Collect the license of every npm package that actually ended up in a bundle.
const packages = new Map();
for (const { metafile } of results) {
  for (const input of Object.keys(metafile.inputs)) {
    const match = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (match) packages.set(match[1], join("node_modules", match[1]));
  }
}
const sections = [...packages].sort(([a], [b]) => a.localeCompare(b)).map(([name, root]) => {
  const meta = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const file = readdirSync(root).find(entry => /^licen[cs]e/i.test(entry));
  if (!file) throw new Error(`No license file for bundled package ${name}`);
  return `${name} ${meta.version} (${meta.license})\n${"-".repeat(72)}\n${readFileSync(join(root, file), "utf8").trim()}\n`;
});
writeFileSync(join(dirname(process.cwd()), "THIRD_PARTY_LICENSES.txt"),
  "Third-party software bundled in static/navigation.js and static/visuals.js.\n" +
  "Generated by frontend/build.mjs. Do not edit directly.\n\n" + sections.join("\n"));
